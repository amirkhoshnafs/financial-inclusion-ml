import pandas as pd

from src.config import MODEL_FEATURES, PROCESSED_DIR, REPORTS_DIR

IN_PATH=PROCESSED_DIR / 'model_table.parquet'
OUT_PATH=REPORTS_DIR / 'model_table_quality.md'

FEATURE_COLS = MODEL_FEATURES

ID_COLS=[
    'respondent_id',
    'economy',
    'economy_code',
    'survey_weight',
]


def fmt_pct(x):
    return f'{100 * x:.1f}%'


def main():
    df=pd.read_parquet(IN_PATH)

    target_counts=df['target'].value_counts().sort_index()
    target_rates=df['target'].value_counts(normalize=True).sort_index()
    missing=df.isna().sum()

    lines=[
        '# Model table quality report',
        '',
        '## Generated file',
        '',
        '`data/processed/model_table.parquet`',
        '',
        'Generated by:',
        '',
        '`python -m src.build_model_table`',
        '',
        '## Shape',
        '',
        f'- Rows: {len(df):,}',
        f'- Columns: {len(df.columns):,}',
        '',
        '## Target',
        '',
        'Target column:',
        '',
        '`target`',
        '',
        'Meaning:',
        '',
        '- 1 = respondent owns an account',
        '- 0 = respondent does not own an account',
        '',
        'Target distribution:',
        '',
        '| target | count | share |',
        '|---:|---:|---:|',
    ]

    for value in target_counts.index:
        lines.append(f'| {value} | {target_counts[value]:,} | {fmt_pct(target_rates[value])} |')

    lines.extend([
        '',
        '## Feature columns',
        '',
    ])

    for col in FEATURE_COLS:
        lines.append(f'- `{col}`')

    lines.extend([
        '',
        '## Metadata columns',
        '',
    ])

    for col in ID_COLS:
        lines.append(f'- `{col}`')

    lines.extend([
        '',
        '## Missing values',
        '',
        '| column | missing |',
        '|---|---:|',
    ])

    for col, value in missing.items():
        if value > 0:
            lines.append(f'| `{col}` | {value:,} |')

    lines.extend([
        '',
        '## Leakage controls',
        '',
        'The model table excludes variables that are components or downstream outcomes of account ownership.',
        '',
        'Excluded examples:',
        '',
        '- `has_financial_institution_account`',
        '- `has_mobile_money_account`',
        '- digital payment behavior',
        '- formal saving behavior',
        '- formal borrowing behavior',
        '- receiving wages, transfers, pensions, or agricultural payments through accounts',
        '',
        'I kept the first feature set intentionally limited so the model uses background characteristics rather than behaviors that are likely downstream of already having an account.',
        '',
        '## Current modeling status',
        '',
        'This table is ready for baseline classification modeling.',
        '',
        'The first model should be a logistic regression baseline with preprocessing for categorical variables and missing values.',
    ])

    OUT_PATH.write_text('\n'.join(lines), encoding='utf-8')

    print('saved')
    print(OUT_PATH)


if __name__ == '__main__':
    main()
